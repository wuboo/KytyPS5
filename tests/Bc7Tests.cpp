// S124: every mode against vectors from an independent decoder (modes 0..3 and 7 with three partitions each).
void TestAllModes() {
	int seen[8] {};
	for (const auto& v: kVectors) {
		const auto b = Bc7Decode(v.block);
		Check(b.ok && b.mode == v.mode, "vector mode");
		seen[v.mode]++;
		for (int i = 0; i < 16; i++) {
			for (int c = 0; c < 4; c++) {
				if (b.texels[i][c] != v.texels[i * 4 + c]) {
					std::fprintf(stderr, "Bc7Tests: mode %d pixel %d channel %d: got %d want %d\n", v.mode, i, c, b.texels[i][c], v.texels[i * 4 + c]);
					Check(false, "vector texel");
				}
			}
		}
	}
	for (int m = 0; m < 8; m++) Check(seen[m] > 0, "a mode has no vector");
}

